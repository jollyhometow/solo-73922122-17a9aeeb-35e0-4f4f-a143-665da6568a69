-- ============================================================================
-- 电表累计读数 -> 区间用电量  数据模型
-- PostgreSQL 13+
--
-- 区间语义: 同一只电表按 UTC 时刻排序, 相邻两条读数 (a, b) 形成
--           左开右闭区间 (a.read_at, b.read_at]
--   - 首条读数之前不存在区间
--   - b.replaced = true (换表后的首条读数): 区间电量缺测 energy_wh = NULL
--   - 否则 energy_wh = b.reading - a.reading, 若为负则加 1_000_000
--     (0..999999 整数 Wh 的单次回绕; 结果不可能再为负)
-- 区间行由数据库函数在写入路径上做持久化的增量维护, 不重扫整只电表。
-- ============================================================================

CREATE TABLE IF NOT EXISTS meters (
    meter_no  TEXT PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- 累计读数
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS meter_readings (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meter_no  TEXT NOT NULL
              REFERENCES meters(meter_no) ON UPDATE CASCADE ON DELETE RESTRICT,
    read_at   TIMESTAMPTZ NOT NULL,        -- UTC 时刻
    reading   INTEGER NOT NULL CHECK (reading BETWEEN 0 AND 999999), -- Wh
    replaced  BOOLEAN NOT NULL DEFAULT false, -- 换表标记: 该读数为新表首读
    CONSTRAINT meter_readings_uk_meter_time UNIQUE (meter_no, read_at)
);

COMMENT ON TABLE meter_readings IS '电表累计读数; 同表同刻唯一';
COMMENT ON COLUMN meter_readings.replaced IS '换表标记=true 时, 以该读数为右端点的区间电量缺测';

-- 按电表取前驱/后继用 (唯一约束本身已是 (meter_no, read_at) 的 B-tree)

-- ---------------------------------------------------------------------------
-- 区间用电量 (左开右闭), 每个非首条读数对应一行
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS reading_intervals (
    meter_no     TEXT NOT NULL
                 REFERENCES meters(meter_no) ON UPDATE CASCADE ON DELETE CASCADE,
    start_read_at TIMESTAMPTZ NOT NULL,    -- 开区间端点 (前驱读数时刻)
    end_read_at   TIMESTAMPTZ NOT NULL,    -- 闭区间端点 (当前读数时刻)
    start_reading INTEGER,                 -- 前驱累计读数 (审计/溯源用)
    end_reading   INTEGER NOT NULL,        -- 右端读数
    energy_wh     INTEGER,                 -- 区间电量; NULL = 缺测(换表)
    CONSTRAINT reading_intervals_pk PRIMARY KEY (meter_no, end_read_at),
    CONSTRAINT reading_intervals_uk_start UNIQUE (meter_no, start_read_at),
    CONSTRAINT reading_intervals_chk_order CHECK (start_read_at < end_read_at),
    CONSTRAINT reading_intervals_chk_energy
        CHECK (energy_wh IS NULL OR energy_wh BETWEEN 0 AND 999999)
);

COMMENT ON TABLE reading_intervals IS '左开右闭区间 (start_read_at, end_read_at] 的电量; energy_wh 为 NULL 表示缺测';

-- 供数按电表 + 时间范围过滤
CREATE INDEX IF NOT EXISTS reading_intervals_idx_meter_end
    ON reading_intervals (meter_no, end_read_at);

-- ============================================================================
-- 区间电量纯函数: 负差值按 1_000_000 单次回绕; 换表 => NULL(缺测)
-- ============================================================================
CREATE OR REPLACE FUNCTION interval_energy(
    p_prev_reading INTEGER,
    p_curr_reading INTEGER,
    p_curr_replaced BOOLEAN
) RETURNS INTEGER
LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE
        WHEN p_curr_replaced THEN NULL
        WHEN p_curr_reading >= p_prev_reading THEN p_curr_reading - p_prev_reading
        ELSE p_curr_reading - p_prev_reading + 1000000
    END;
$$;
